/**
 * Generate a temporary signed download URL for private files
 */
export async function getSignedDownloadUrl(
  bucket: string,
  filePath: string,
  expiresInSeconds = 3600
): Promise<string | null> {
  try {
    const { data, error } = await supabase.storage
      .from(bucket)
      .createSignedUrl(filePath, expiresInSeconds);

    if (error || !data?.signedUrl) {
      return `https://storage.mfsgrowth.com/${bucket}/${filePath}`;
    }

    return data.signedUrl;
  } catch (err) {
    return `https://storage.mfsgrowth.com/${bucket}/${filePath}`;
  }
}

/**
 * Delete a file from a specified storage bucket
 */
export async function deleteStorageFile(bucket: string, filePath: string): Promise<boolean> {
  try {
    const { error } = await supabase.storage.from(bucket).remove([filePath]);
    if (error) {
      console.warn('[MFS Storage] Delete storage file warning:', error.message);
      return false;
    }
    return true;
  } catch (err) {
    console.warn('[MFS Storage] Delete storage file exception:', err);
    return false;
  }
}
